#!/usr/bin/env python3
"""Generate src/keymap_file/zmk-defines.h from ZMK's dt-bindings headers.

Every object-like macro from the headers a keymap usually includes is expanded with the C
preprocessor and evaluated to plain numbers, so the overlay's small preprocessor doesn't need
the (large) headers themselves. Function-like macros keymaps use directly (LS(), LA(), ...) are
written by hand at the top of the output.

Usage: tools/gen-zmk-defines.py ZMK_CHECKOUT/app/include COMMIT > src/keymap_file/zmk-defines.h
"""

import re
import subprocess
import sys
from pathlib import Path

HEADERS = [
    "keys.h", "modifiers.h", "bt.h", "outputs.h", "rgb.h", "backlight.h", "ext_power.h",
    "reset.h", "pointing.h", "mouse.h",
]

FUNCTION_MACROS = """\
#define BIT(n) (1 << (n))
#define ZMK_HID_USAGE(page, id) ((page << 16) | id)
#define APPLY_MODS(mods, keycode) (mods << 24 | keycode)
#define LC(keycode) APPLY_MODS(0x01, keycode)
#define LS(keycode) APPLY_MODS(0x02, keycode)
#define LA(keycode) APPLY_MODS(0x04, keycode)
#define LG(keycode) APPLY_MODS(0x08, keycode)
#define RC(keycode) APPLY_MODS(0x10, keycode)
#define RS(keycode) APPLY_MODS(0x20, keycode)
#define RA(keycode) APPLY_MODS(0x40, keycode)
#define RG(keycode) APPLY_MODS(0x80, keycode)
#define MOVE_Y(vert) ((vert) & 0xFFFF)
#define MOVE_X(hor) (((hor) & 0xFFFF) << 16)
#define MOVE(hor, vert) (MOVE_X(hor) + MOVE_Y(vert))
"""

DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_]\w*)(\(?)", re.M)


def evaluate(expr: str) -> int:
    expr = re.sub(r"\b(0x[0-9A-Fa-f]+|\d+)[uUlL]+\b", r"\1", expr)
    return eval(expr, {"__builtins__": {}})  # trusted input: ZMK headers via cpp


def main() -> None:
    include, commit = Path(sys.argv[1]), sys.argv[2]
    names = []
    for h in HEADERS:
        text = (include / "dt-bindings/zmk" / h).read_text()
        names += [m[1] for m in DEFINE.finditer(text) if not m[2]]
    names = list(dict.fromkeys(n for n in names if not n.startswith("ZMK_POINTING_DEFAULT")))
    src = "#define BIT(n) (1 << (n))\n"
    src += "".join(f"#include <dt-bindings/zmk/{h}>\n" for h in HEADERS)
    src += "".join(f"@@{i}@@ {n}\n" for i, n in enumerate(names))
    out = subprocess.run(
        ["cpp", "-P", "-x", "assembler-with-cpp", "-I", str(include), "-"],
        input=src, capture_output=True, text=True, check=True,
    ).stdout
    print(f"// Generated by tools/gen-zmk-defines.py from zmk {commit} (app/include/dt-bindings/zmk).")
    print("// Do not edit; regenerate instead.")
    print(FUNCTION_MACROS, end="")
    for line in out.splitlines():
        m = re.match(r"@@(\d+)@@ (.*)", line)
        if not m:
            continue
        name, expansion = names[int(m[1])], m[2].strip()
        if expansion == name or "@@" in expansion:
            continue
        try:
            values = [evaluate(expansion)]
        except Exception:
            try:
                values = [evaluate(t) for t in expansion.split()]
            except Exception:
                print(f"skipping {name}: {expansion}", file=sys.stderr)
                continue
        print(f"#define {name} " + " ".join(hex(v) if v > 9 else str(v) for v in values))


main()
